#include "../MercuryLan/mercury_codec.h"

#include <assert.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>

static void setCrc(uint8_t frame[23]) {
  const uint16_t crc = mercury::crc16(frame, 21);
  frame[21] = uint8_t(crc);
  frame[22] = uint8_t(crc >> 8);
}

int main() {
  // Independent published CRC16/MODBUS check value.
  const uint8_t text[] = "123456789";
  assert(mercury::crc16(text, 9) == 0x4B37);

  // Wire request from Wiren Board's Mercury 200 test fixture.
  uint8_t request[7];
  const uint8_t wbRequest[] = {0xFE, 0x12, 0x34, 0x56, 0x27, 0x36, 0xD8};
  mercury::makeRequest(0xFE123456UL, request);
  assert(memcmp(request, wbRequest, sizeof(request)) == 0);
  const uint8_t photoRequest[] = {0x00, 0x09, 0xF0, 0x89, 0x27, 0x00, 0x25};
  mercury::makeRequest(651401UL, request);
  assert(memcmp(request, photoRequest, sizeof(request)) == 0);

  // External response fixture, not generated by this implementation.
  // wirenboard/wb-mqtt-serial test/mercury200_expectations.cpp
  // Blob SHA bcc87fdf6adff0f35b419f86133af73439282dc0.
  const uint8_t wbReply[23] = {0xFE, 0x12, 0x34, 0x56, 0x27,
      0x00, 0x06, 0x21, 0x42, 0x00, 0x02, 0x08, 0x34,
      0x00, 0x01, 0x11, 0x11, 0x00, 0x02, 0x22, 0x22, 0x2B, 0x25};
  uint32_t externalValues[4] = {0, 0, 0, 0};
  assert(mercury::decodeResponse(wbReply, 23, 0xFE123456UL, externalValues) == mercury::OK);
  assert(externalValues[0] == 62142 && externalValues[1] == 20834 &&
         externalValues[2] == 11111 && externalValues[3] == 22222);

  // Fixed synthetic meter payload: 1234.56, 78.90, 0.00, 999999.99 kWh.
  // CRC below only prepares test data; wire order is checked independently above.
  uint8_t reply[23] = {0x00, 0x09, 0xF0, 0x89, 0x27,
      0x00, 0x12, 0x34, 0x56, 0x00, 0x00, 0x78, 0x90,
      0x00, 0x00, 0x00, 0x00, 0x99, 0x99, 0x99, 0x99, 0, 0};
  setCrc(reply);
  uint32_t values[4] = {7, 7, 7, 7};
  assert(mercury::decodeResponse(reply, 23, 651401UL, values) == mercury::OK);
  assert(values[0] == 123456 && values[1] == 7890 &&
         values[2] == 0 && values[3] == 99999999UL);
  assert(mercury::decodeResponse(reply, 22, 651401UL, values) == mercury::BAD_LENGTH);
  assert(mercury::decodeResponse(reply, 23, 651402UL, values) == mercury::WRONG_ADDRESS);

  uint8_t bad[23];
  memcpy(bad, reply, 23);
  bad[4] = 0x63;
  assert(mercury::decodeResponse(bad, 23, 651401UL, values) == mercury::WRONG_COMMAND);
  memcpy(bad, reply, 23);
  bad[9] ^= 1;
  assert(mercury::decodeResponse(bad, 23, 651401UL, values) == mercury::BAD_CRC);
  memcpy(bad, reply, 23);
  bad[17] = 0xFA;
  setCrc(bad);
  uint32_t untouched[4] = {7, 7, 7, 7};
  assert(mercury::decodeResponse(bad, 23, 651401UL, untouched) == mercury::BAD_BCD);
  for (int i = 0; i < 4; ++i) assert(untouched[i] == 7);

  // Echo + noise + damaged frame + valid frame must recover without a flush.
  mercury::Decoder stream(651401UL);
  assert(stream.failure() == mercury::NO_REPLY);
  for (int i = 0; i < 7; ++i) assert(!stream.feed(request[i], values));
  assert(!stream.feed(0x42, values));
  assert(!stream.feed(0xFF, values));
  for (int i = 0; i < 23; ++i) assert(!stream.feed(bad[i], values));
  assert(stream.failure() == mercury::BAD_BCD);
  for (int i = 0; i < 22; ++i) assert(!stream.feed(reply[i], values));
  assert(stream.feed(reply[22], values));
  assert(values[0] == 123456 && values[3] == 99999999UL);

  mercury::Decoder noEcho(651401UL);
  for (int i = 0; i < 22; ++i) assert(!noEcho.feed(reply[i], values));
  assert(noEcho.feed(reply[22], values));

  // A truncated reply must never become a false successful zero reading.
  mercury::Decoder truncated(651401UL);
  for (int i = 0; i < 22; ++i) assert(!truncated.feed(reply[i], values));
  assert(truncated.failure() == mercury::INVALID_FRAME);
  puts("Arduino codec: all protocol and stream tests passed");
  return 0;
}
